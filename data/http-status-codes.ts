export function searchStatusCodes(
  query: string,
  protocol?: Protocol
): StatusCodeEntry[] {
  const q = query.trim().toLowerCase()
  let list = protocol ? ALL_STATUS_CODES.filter((e) => e.protocol === protocol) : ALL_STATUS_CODES
  if (!q) return list
  return list.filter(
    (e) =>
      String(e.code).includes(q) ||
      e.name.toLowerCase().includes(q) ||
      e.description.toLowerCase().includes(q) ||
      e.category.toLowerCase().includes(q) ||
      e.categoryName.toLowerCase().includes(q) ||
      e.whenWhereWhy.toLowerCase().includes(q)
  )
}
